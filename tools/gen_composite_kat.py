#!/usr/bin/env python3
"""
Generate the known-answer test data used by the three P15 implementations from the
test vectors of the composite ML-KEM draft (github.com/lamps-wg/draft-composite-kem,
src/testvectors.json).

Two vectors are taken:
  * id-MLKEM1024-RSA3072-SHA3-256: checks the hybrid end to end -- PKCS#8 layout
    (seed || RSAPrivateKey), ciphertext split, RSA-OAEP parameters and the combiner
    SHA3-256(ss_ML || ss_RSA || ct_RSA || RSAPublicKey || "MLKEM1024-RSAOAEP3072").
  * id-alg-ml-kem-1024: checks pure ML-KEM-1024 decapsulation from an RFC 9935
    seed-format PKCS#8 key.

Usage: python tools/gen_composite_kat.py /path/to/draft-composite-kem
"""
import base64, json, os, subprocess, sys, textwrap

repo = sys.argv[1]
commit = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
tests = {t["tcId"]: t for t in json.load(open(os.path.join(repo, "src", "testvectors.json")))["tests"]}
hyb, ml = tests["id-MLKEM1024-RSA3072-SHA3-256"], tests["id-alg-ml-kem-1024"]
rsa_pub = base64.b64encode(base64.b64decode(hyb["ek"])[1568:]).decode()
fields = {
    "HYB_DK_PKCS8": hyb["dk_pkcs8"], "HYB_RSA_PUB": rsa_pub, "HYB_C": hyb["c"], "HYB_K": hyb["k"],
    "ML_DK_PKCS8": ml["dk_pkcs8"], "ML_C": ml["c"], "ML_K": ml["k"],
}
src = f"lamps-wg/draft-composite-kem@{commit} src/testvectors.json"
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)


def chunks(s, n=76):
    return textwrap.wrap(s, n)


# C header
with open(os.path.join(root, "native", "src", "composite_kat.h"), "w") as f:
    f.write(f"/* Generated by tools/gen_composite_kat.py from {src}. Do not edit. */\n")
    f.write(f'static const char KAT_SOURCE[] = "{src}";\n')
    for k, v in fields.items():
        f.write(f"static const char KAT_{k}[] =\n")
        f.write("\n".join(f'    "{c}"' for c in chunks(v)) + ";\n")

# Java class
jdir = os.path.join(root, "android", "app", "src", "main", "java", "es", "usal", "p15bench")
with open(os.path.join(jdir, "CompositeKat.java"), "w") as f:
    f.write(f"// Generated by tools/gen_composite_kat.py from {src}. Do not edit.\n")
    f.write("package es.usal.p15bench;\n\nfinal class CompositeKat {\n    private CompositeKat() {}\n")
    f.write(f'    static final String SOURCE = "{src}";\n')
    for k, v in fields.items():
        f.write(f"    static final String {k} =\n")
        f.write(" +\n".join(f'        "{c}"' for c in chunks(v)) + ";\n")
    f.write("}\n")

# JavaScript module
with open(os.path.join(root, "web", "src", "composite_kat.js"), "w") as f:
    f.write(f"// Generated by tools/gen_composite_kat.py from {src}. Do not edit.\n")
    f.write(f"export const SOURCE = '{src}';\n")
    for k, v in fields.items():
        f.write(f"export const {k} =\n" + " +\n".join(f"  '{c}'" for c in chunks(v)) + ";\n")

print("written for", src)
